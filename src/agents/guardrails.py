"""
src/agents/guardrails.py
─────────────────────────────────────────────────────────────
Granite Guardian safety filter.
Wraps the GraniteGuardianClient to provide:
  - Input screening (block harmful user inputs)
  - Output screening (redact/modify unsafe agent responses)
  - Automatic clinical disclaimer injection for health content
"""
from __future__ import annotations

import logging
import re

from src.services.watsonx_service import get_guardian_client

logger = logging.getLogger(__name__)

CLINICAL_DISCLAIMER = (
    "\n\n---\n"
    "⚕️ **Medical Disclaimer:** This information is generated by an AI and is "
    "intended for general wellness and informational purposes only. It does not "
    "constitute professional medical advice, diagnosis, or treatment. Always "
    "consult a qualified healthcare professional before making dietary or medical "
    "decisions, especially if you have a chronic health condition."
)

RISK_PATTERNS = [
    r"\bcure[sd]?\b",
    r"\btreat(ment|ing|s)?\b",
    r"\bprescri(be|ption)\b",
    r"\bdiagnos(e|is|ed)\b",
    r"\bmedication\s+dose\b",
    r"\bstop\s+(your|taking)\s+\w+\s*medication\b",
    r"\binstead\s+of\s+(your\s+)?doctor\b",
]

_RISK_RE = re.compile("|".join(RISK_PATTERNS), re.IGNORECASE)


class GuardrailsFilter:
    """
    Two-stage safety filter:
      1. Regex pre-screen (fast, no API call needed for obvious cases)
      2. Granite Guardian deep evaluation (for borderline content)
    """

    def __init__(self, use_llm_guardian: bool = True) -> None:
        self._use_llm = use_llm_guardian

    # ── Input guard ───────────────────────────────────────────

    def screen_input(self, user_input: str) -> tuple[bool, str]:
        """
        Screen user input for harmful intent.

        Returns:
            (is_safe, reason) — if not safe, the reason explains why.
        """
        if _RISK_RE.search(user_input):
            return False, "Input contains potentially harmful medical request patterns."

        if self._use_llm:
            verdict = get_guardian_client().check(user_input)
            if not verdict.get("safe", True):
                return False, verdict.get("reason", "Flagged by safety model.")

        return True, "OK"

    # ── Output guard ──────────────────────────────────────────

    def screen_output(self, agent_output: str, is_health_content: bool = False) -> str:
        """
        Post-process agent output.
        - Runs LLM safety check if enabled.
        - Injects clinical disclaimer for health-related outputs.
        - Returns modified text.
        """
        if self._use_llm:
            verdict = get_guardian_client().check(agent_output)
            if not verdict.get("safe", True):
                category = verdict.get("risk_category", "safety")
                logger.warning(
                    "Output flagged by Guardian [%s]: %s",
                    category,
                    verdict.get("reason"),
                )
                agent_output = (
                    f"[Content moderated — {category}]\n\n"
                    "I can provide general wellness guidance, but this specific "
                    "content was flagged by our safety system. Please consult a "
                    "qualified healthcare professional for personalised advice."
                )

        if is_health_content and CLINICAL_DISCLAIMER not in agent_output:
            agent_output += CLINICAL_DISCLAIMER

        return agent_output

    # ── Convenience wrapper for agents ───────────────────────

    def safe_generate(
        self,
        prompt_fn,  # Callable[[], str]
        is_health_content: bool = False,
    ) -> str:
        """
        Execute a generation function and apply output guardrails.
        Usage:
            result = guardrails.safe_generate(
                lambda: llm_client.generate(prompt),
                is_health_content=True
            )
        """
        raw_output = prompt_fn()
        return self.screen_output(raw_output, is_health_content=is_health_content)
